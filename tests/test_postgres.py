def test_prepared_chart_rows_and_totals_on_real_postgres(pg,tmp_path):
    from test_tvl_api import run,DAY,PARENT,CHILD
    from yearn_data.tvl_api import TvlStore,TvlDataset
    from yearn_data.tvl_history_cache import prepare
    conn,_=pg
    init_db(conn)
    run(conn,1,DAY,[(PARENT,'100'),(CHILD,'100')],[(CHILD,'50')])
    run(conn,2,DAY+86400,[(PARENT,'200'),(CHILD,'200')],[(CHILD,'100')])
    original=TvlStore('neon',tmp_path/'tvl').get()
    expected=original.history(interval='daily')
    constant=original.history(group='vault',interval='daily',constant=True)
    prepare(original)
    cached=TvlDataset(original.manifest)
    assert cached.history(interval='daily')==expected
    assert cached.history(group='vault',interval='daily',constant=True)==constant
    assert cached.history(interval='daily',start=DAY+100*86400)['chart']==[]
