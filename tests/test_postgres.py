def test_parameter_conversion_preserves_quoted_question_marks_and_modulo():
    statement = "SELECT ? AS value, '?' AS literal, 7%3 AS rest WHERE ? LIKE '%?%' -- ? comment\n"
    assert parameters(statement) == "SELECT %s AS value, '?' AS literal, 7%%3 AS rest WHERE %s LIKE '%%?%%' -- ? comment\n"


def test_schema_translation_preserves_default_text_and_forward_references():
    statements = schema_statements("""
        CREATE TABLE child(id INTEGER, parent INTEGER REFERENCES parent(id), value REAL, note TEXT DEFAULT 'INTEGER; REAL');
        CREATE TABLE parent(id INTEGER PRIMARY KEY AUTOINCREMENT);
    """)
    assert 'CREATE TABLE parent' in statements[0]
    assert 'GENERATED BY DEFAULT AS IDENTITY' in statements[0]
    assert 'DOUBLE PRECISION' in statements[1]
    assert "DEFAULT 'INTEGER; REAL'" in statements[1]


